export const DICT: Record<Lang, Record<string, string>> = { zh: {}, en: {} };
for (const [k, [zh, en]] of Object.entries(ENTRIES)) {
  DICT.zh[k] = zh;
  DICT.en[k] = en;
}

/** 翻译：参数值以 "@" 开头时，把它当作另一个 key 再翻译（用于队友名字等） */
export function translate(lang: Lang, key: string, params?: Params): string {
  const raw = DICT[lang][key] ?? DICT.zh[key] ?? key;
  if (!params) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) => {
    const v = params[name];
    if (v === undefined) return `{${name}}`;
    return typeof v === 'string' && v.startsWith('@') ? translate(lang, v.slice(1)) : String(v);
  });
}
